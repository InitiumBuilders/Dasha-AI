/* Bake api/_prompt.js, her offline fallback mind, from PROMPT/ as it stands in this repository.

   api/_mind.js streams her mind from GitHub on every request and reads api/_prompt.js only when that fetch
   fails. It requires the file at import time all the same, so the file has to exist for the functions to load,
   and that is why it is committed.

       node scripts/assemble-prompt.js

   Run it again whenever PROMPT/ changes. The fallback is read only while GitHub is unreachable, so a stale one
   goes unseen until then.

   What is baked: SPINE.md, then every skill and every reference section named in INDEX.json, in that order.
   On the fallback she has no library to load from, so all of it has to sit in the one prompt.

   The api/_prompt.js committed here comes from the Dash Support Team's own build, which bakes it from the three
   source files that PROMPT/ is split from. Those three files are kept with the site and are not in this
   repository. At the same version, both bakes hold the same skills and the same reference sections. */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(ROOT, 'PROMPT', f), 'utf8').trim();

const index = JSON.parse(read('INDEX.json'));
const spine = read('SPINE.md');
const V = read('VERSION').split('\n')[0].trim();

/* a library file is named by the index, so the name is checked before it is read */
const LIBRARY_FILE = /^(skills|knowledge)\/[A-Za-z0-9._-]+\.md$/;
function part(entry) {
  if (!entry || !LIBRARY_FILE.test(String(entry.file || ''))) throw new Error('INDEX.json names a file outside skills/ or knowledge/: ' + JSON.stringify(entry && entry.file));
  return read(entry.file);
}
const skills = index.skills.map(part).join('\n\n');
const know = index.knowledge.map(part).join('\n\n');

const full = spine + '\n\n' + '='.repeat(8) + ' SKILLS REGISTRY ' + '='.repeat(8) + '\n\n' + skills
  + '\n\n' + '='.repeat(8) + ' DASH KNOWLEDGE PACK ' + '='.repeat(8) + '\n\n' + know;

const out = '/* AUTO-GENERATED by scripts/assemble-prompt.js from PROMPT/. Do not edit. */\n'
  + 'const SYSTEM_PROMPT = ' + JSON.stringify(full) + ';\n'
  + 'const VERSION = ' + JSON.stringify(V) + ';\n'
  + 'module.exports = { SYSTEM_PROMPT, VERSION };\n';

fs.writeFileSync(path.join(ROOT, 'api', '_prompt.js'), out);
console.log('baked api/_prompt.js: ' + full.length + ' chars, ' + index.skills.length + ' skills, '
  + index.knowledge.length + ' reference sections, version ' + V);
